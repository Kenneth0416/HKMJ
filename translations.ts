export const getTranslation = (lang: Language, key: keyof typeof translations['zh-HK'], params?: Record<string, string | number>) => {
  let text = translations[lang][key] || translations['zh-HK'][key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  return text;
};